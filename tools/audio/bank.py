#!/usr/bin/env python3
"""Writes src/shared/SoundBank.luau from tools/audio/sheets.json and
tools/audio/sound_ids.json (upload.py runs it after uploading).

  python3 tools/audio/bank.py"""

import json
import os
import shutil
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "shared", "SoundBank.luau")

# palette group -> the game's volume group (SoundGroup)
GROUP = {"ui": "UI", "gameplay": "SFX", "thunder": "SFX", "rewards": "SFX", "ambience": "Ambience"}
VOLUME = {"UI": 0.5, "SFX": 0.7, "Ambience": 0.5}  # default volumes (files are already loudness-matched)
VOLUME_OVERRIDE = {"hover": 0.25, "volts_tick": 0.3}  # meant to sit very quietly
VARY = ("click", "hover", "toast", "volts_tick", "catch_", "strike_crack_", "tank_glug", "gate_bump")  # ±4% pitch


def main():
    sheets = json.load(open(os.path.join(HERE, "sheets.json")))
    ids = json.load(open(os.path.join(HERE, "sound_ids.json")))
    lines = []
    for name in sorted(sheets["sounds"]):
        s = sheets["sounds"][name]
        group = GROUP[s["group"]]
        volume = VOLUME_OVERRIDE.get(name, VOLUME[group])
        vary = any(name == v or (v.endswith("_") and name.startswith(v)) for v in VARY)
        lines.append(
            f"\t{name} = {{ id = \"rbxassetid://{ids[s['file']]['assetId']}\", file = \"{s['file']}\", "
            f"start = {s['start']}, length = {s['length']}, loop = {str(s['loop']).lower()}, "
            f"group = \"{group}\", volume = {volume}, vary = {str(vary).lower()} }},"
        )
    with open(OUT, "w") as f:
        f.write(
            "--!strict\n"
            "-- Every sound in the game: generated by tools/audio/bank.py from\n"
            "-- tools/audio/sheets.json and sound_ids.json. Don't edit by hand: change\n"
            "-- tools/audio/sfx.py, then run sfx.py, review.py, pack.py and upload.py.\n"
            "--\n"
            "-- One-shot effects share a few uploaded sheets: a sound is the region\n"
            "-- start .. start + length (seconds) of its file. group is the SoundGroup\n"
            "-- it plays in, volume its default volume, vary: random ±4% pitch.\n\n"
            "export type Entry = {\n"
            "\tid: string,\n\tfile: string,\n\tstart: number,\n\tlength: number,\n\tloop: boolean,\n"
            "\tgroup: string,\n\tvolume: number,\n\tvary: boolean,\n}\n\n"
            "local SoundBank: { [string]: Entry } = {\n" + "\n".join(lines) + "\n}\n\n"
            "return table.freeze(SoundBank)\n"
        )
    if shutil.which("stylua"):
        subprocess.run(["stylua", OUT], check=True)
    print(f"wrote src/shared/SoundBank.luau ({len(lines)} sounds)")


if __name__ == "__main__":
    main()
