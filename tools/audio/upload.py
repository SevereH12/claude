#!/usr/bin/env python3
"""Uploads the packed sound files (tools/audio/sheets.json) to Roblox
through the Open Cloud Assets API, owned by the Super Studio group (the
group that owns the game, so the game may play them). Only files whose
content changed since the last upload are sent. Writes the ids to
tools/audio/sound_ids.json, then regenerates src/shared/SoundBank.luau.

  python3 tools/audio/upload.py [outdir]      (default tools/audio/out)

The API key is sent as the x-api-key header from $ROBLOX_API_KEY, or added
by the network proxy when that variable isn't set. It needs "Assets: read
and write" for the group."""

import hashlib
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
API = "https://apis.roblox.com/assets/v1"
GROUP_ID = "7889739"
IDS = os.path.join(HERE, "sound_ids.json")


class Refused(Exception):
    pass


def curl(args):
    key = os.environ.get("ROBLOX_API_KEY")
    header = ["-H", f"x-api-key: {key}"] if key else []
    out = subprocess.run(
        ["curl", "-sS", "-m", "120", "-w", "\n%{http_code}", *header, *args], capture_output=True, text=True
    )
    body, _, code = out.stdout.rpartition("\n")
    if code in ("401", "403"):
        raise Refused(
            f"HTTP {code}: {body or out.stderr}\n\nThe API key can't upload for the group. On "
            "create.roblox.com > Open Cloud > API Keys, edit the key and add the 'assets' API "
            "with 'Read' and 'Write' for the Super Studio group (7889739), then run this again."
        )
    if code == "429" or (not code.startswith("2") and ("quota" in body.lower() or "limit" in body.lower())):
        raise Refused(f"HTTP {code}: rate or upload limit reached: {body}")
    if not code.startswith("2"):
        raise SystemExit(f"HTTP {code}: {body or out.stderr}")
    return json.loads(body) if body.strip() else {}


def digest(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def upload(path, name):
    request = {
        "assetType": "Audio",
        "displayName": f"Storm Bottler {name}",
        "description": f"Storm Bottler Simulator sound effects ({name}), generated by the game's own tools.",
        "creationContext": {"creator": {"groupId": GROUP_ID}},
    }
    op = curl(["-X", "POST", f"{API}/assets", "-F", f"request={json.dumps(request)};type=application/json",
               "-F", f"fileContent=@{path};type=audio/ogg"])
    path_ = op.get("path") or f"operations/{op.get('operationId')}"
    for _ in range(60):
        if op.get("done"):
            break
        time.sleep(2)
        op = curl([f"{API}/{path_}"])
    if not op.get("done"):
        raise SystemExit(f"{name}: upload still processing after 2 minutes ({path_})")
    if "error" in op:
        raise SystemExit(f"{name}: upload failed: {op['error']}")
    return op["response"]["assetId"]


def moderation(asset_id):
    info = curl([f"{API}/assets/{asset_id}"])
    return (info.get("moderationResult") or {}).get("moderationState", "Unknown")


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "out")
    sheets = json.load(open(os.path.join(HERE, "sheets.json")))
    ids = json.load(open(IDS)) if os.path.exists(IDS) else {}
    uploaded = 0
    try:
        for name, info in sheets["files"].items():
            path = os.path.join(out, info["path"])
            h = digest(path)
            have = ids.get(name)
            if have and have.get("hash") == h:
                print(f"same     {name}: {have['assetId']}")
            else:
                asset = upload(path, name)
                ids[name] = {"assetId": asset, "hash": h}
                uploaded += 1
                print(f"uploaded {name}: {asset}")
                with open(IDS, "w") as f:  # after each one, so a stop keeps what's done
                    json.dump(ids, f, indent=1)
                    f.write("\n")
    except Refused as err:
        print(f"STOPPED after {uploaded} upload(s): {err}")
        sys.exit(2)
    for name in sheets["files"]:
        state = moderation(ids[name]["assetId"])
        ids[name]["moderation"] = state
        print(f"moderation {name}: {state}")
    with open(IDS, "w") as f:
        json.dump(ids, f, indent=1)
        f.write("\n")
    subprocess.run([sys.executable, os.path.join(HERE, "bank.py")], check=True)


if __name__ == "__main__":
    main()
